"""Check that commit messages follow Conventional Commits 1.0.

    py scripts/check_commit_msg.py .git/COMMIT_EDITMSG     # used by the commit-msg hook
    git log --format=%s origin/main..HEAD | py scripts/check_commit_msg.py --stdin   # CI

Rules (subject line):
  type(scope)!: description
  - type is one of feat, fix, docs, style, refactor, perf, test, build, ci, chore, revert
  - scope is optional, lowercase letters, digits and hyphens
  - "!" marks a breaking change; a body may also carry a "BREAKING CHANGE:" footer
  - description is non-empty, has no trailing period and the whole subject is at most 72 characters
Merge, revert and fixup/squash commits generated by git are accepted as they are.
"""

from __future__ import annotations

import re
import sys
from pathlib import Path

TYPES = ["feat", "fix", "docs", "style", "refactor", "perf", "test", "build", "ci", "chore", "revert"]
SUBJECT = re.compile(rf"^({'|'.join(TYPES)})(\([a-z0-9-]+\))?(!)?: (\S.*)$")
GIT_GENERATED = re.compile(r"^(Merge |Revert \"|fixup! |squash! )")
MAX_SUBJECT = 72


def check_subject(subject: str) -> list[str]:
    if GIT_GENERATED.match(subject):
        return []
    match = SUBJECT.match(subject)
    if not match:
        return [
            f'"{subject}" does not match "type(scope)!: description" with type in {", ".join(TYPES)}',
        ]
    errors = []
    if len(subject) > MAX_SUBJECT:
        errors.append(f"subject is {len(subject)} characters; the limit is {MAX_SUBJECT}")
    if match.group(4).rstrip().endswith("."):
        errors.append("subject must not end with a period")
    return errors


def check_message(message: str) -> list[str]:
    """Validate a full commit message: the subject, and a blank line before any body."""
    lines = [line for line in message.replace("\r\n", "\n").split("\n") if not line.startswith("#")]
    while lines and not lines[0].strip():
        lines.pop(0)
    if not lines:
        return ["commit message is empty"]
    errors = check_subject(lines[0])
    if len(lines) > 1 and lines[1].strip():
        errors.append("leave a blank line between the subject and the body")
    return errors


def main(argv: list[str]) -> int:
    if hasattr(sys.stderr, "reconfigure"):
        sys.stderr.reconfigure(encoding="utf-8")
    args = argv[1:]
    if args == ["--stdin"]:
        subjects = [line.strip() for line in sys.stdin.read().splitlines() if line.strip()]
        failures = [(subject, errors) for subject in subjects if (errors := check_subject(subject))]
        for subject, errors in failures:
            for error in errors:
                print(f"- {subject}: {error}", file=sys.stderr)
        if failures:
            print(f"{len(failures)} commit(s) are not conventional.", file=sys.stderr)
            return 1
        print(f"OK: {len(subjects)} commit(s) are conventional.")
        return 0

    if len(args) != 1:
        print("usage: check_commit_msg.py <message-file> | --stdin", file=sys.stderr)
        return 2
    errors = check_message(Path(args[0]).read_text(encoding="utf-8"))
    if errors:
        print("Commit message is not a Conventional Commit:", file=sys.stderr)
        for error in errors:
            print(f"- {error}", file=sys.stderr)
        print('Example: "feat(scripts): add mutation comparison table"', file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
